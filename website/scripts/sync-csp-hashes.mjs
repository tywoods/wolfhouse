#!/usr/bin/env node
/**
 * After `astro build`, extract inline <script> / <style> bodies from dist HTML,
 * compute CSP sha256 hashes, and write them into:
 *   - security/headers.contract.json (inlineHashes)
 *   - public/_headers (and dist/_headers if present)
 *
 * Prefer external scripts; hashes cover unavoidable Astro island bootstrap only.
 * Never adds 'unsafe-eval' or 'unsafe-inline'.
 */
import { createHash } from 'node:crypto';
import { existsSync, readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const DIST = join(ROOT, 'dist');
const CONTRACT_PATH = join(ROOT, 'security/headers.contract.json');
const HEADERS_PUBLIC = join(ROOT, 'public/_headers');
const HEADERS_DIST = join(DIST, '_headers');

function sha256Csp(content) {
  const hash = createHash('sha256').update(content, 'utf8').digest('base64');
  return `'sha256-${hash}'`;
}

function collectHtmlFiles(dir) {
  const out = [];
  function walk(d) {
    for (const name of readdirSync(d)) {
      const abs = join(d, name);
      const st = statSync(abs);
      if (st.isDirectory()) walk(abs);
      else if (name.endsWith('.html')) out.push(abs);
    }
  }
  walk(dir);
  return out.sort();
}

/** Extract raw inline script/style bodies (no src= scripts). */
function extractInline(html, tag) {
  const bodies = [];
  const re = new RegExp(`<${tag}\\b([^>]*)>([\\s\\S]*?)<\\/${tag}>`, 'gi');
  let m;
  while ((m = re.exec(html)) !== null) {
    const attrs = m[1] || '';
    if (/\bsrc\s*=/i.test(attrs)) continue;
    bodies.push(m[2]);
  }
  return bodies;
}

function buildCsp({ scriptHashes, styleHashes }) {
  const scriptSrc = ["'self'", ...scriptHashes].join(' ');
  const styleSrc = ["'self'", ...styleHashes].join(' ');
  return [
    "default-src 'self'",
    `script-src ${scriptSrc}`,
    `style-src ${styleSrc}`,
    "img-src 'self' data:",
    "font-src 'self'",
    "connect-src 'self'",
    "frame-src 'none'",
    "object-src 'none'",
    "base-uri 'self'",
    "form-action 'self'",
    "frame-ancestors 'none'",
  ].join('; ');
}

function renderHeadersFile(csp) {
  return `# Luna Front Desk marketing site — static host security headers
# Format: Cloudflare Pages / Netlify _headers (copied into dist/ on build).
# Platform-neutral contract: security/headers.contract.json
#
# HSTS caveat: emit only over HTTPS. Do not send on http://127.0.0.1 local preview.
# Preview hosts may set HSTS for that hostname; do not add '; preload' until
# production apex HTTPS is intentional and stable.
# Regenerated by: node scripts/sync-csp-hashes.mjs (after npm run build)

/*
  Content-Security-Policy: ${csp}
  X-Content-Type-Options: nosniff
  Referrer-Policy: strict-origin-when-cross-origin
  Permissions-Policy: accelerometer=(), camera=(), geolocation=(), gyroscope=(), magnetometer=(), microphone=(), payment=(), usb=()
  Strict-Transport-Security: max-age=31536000; includeSubDomains
  X-Frame-Options: DENY
`;
}

if (!existsSync(join(DIST, 'index.html'))) {
  console.error('sync-csp-hashes: dist/index.html missing — run npm run build first');
  process.exit(1);
}

const scriptSet = new Set();
const styleSet = new Set();

for (const file of collectHtmlFiles(DIST)) {
  const html = readFileSync(file, 'utf8');
  for (const body of extractInline(html, 'script')) {
    scriptSet.add(sha256Csp(body));
  }
  for (const body of extractInline(html, 'style')) {
    styleSet.add(sha256Csp(body));
  }
}

const scriptHashes = [...scriptSet].sort();
const styleHashes = [...styleSet].sort();
const csp = buildCsp({ scriptHashes, styleHashes });

if (csp.includes('unsafe-eval') || scriptHashes.some((h) => h.includes('unsafe'))) {
  console.error('sync-csp-hashes: refusing unsafe tokens');
  process.exit(1);
}

const contract = JSON.parse(readFileSync(CONTRACT_PATH, 'utf8'));
contract.inlineHashes = {
  script: scriptHashes,
  style: styleHashes,
  generatedBy: 'scripts/sync-csp-hashes.mjs',
  note: 'Populated from dist HTML after build. Prefer external scripts; hashes cover unavoidable Astro island bootstrap only.',
};
// Keep directive placeholders honest for docs readers.
contract.headers['Content-Security-Policy'].directives['script-src'] = [
  "'self'",
  ...scriptHashes,
];
contract.headers['Content-Security-Policy'].directives['style-src'] = [
  "'self'",
  ...styleHashes,
];

writeFileSync(CONTRACT_PATH, `${JSON.stringify(contract, null, 2)}\n`);
const headersBody = renderHeadersFile(csp);
writeFileSync(HEADERS_PUBLIC, headersBody);
writeFileSync(HEADERS_DIST, headersBody);

console.log(`sync-csp-hashes: ${scriptHashes.length} script hash(es), ${styleHashes.length} style hash(es)`);
console.log('sync-csp-hashes: wrote security/headers.contract.json, public/_headers, dist/_headers');
