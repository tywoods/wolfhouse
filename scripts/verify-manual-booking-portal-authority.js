'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const src = fs.readFileSync(path.join(root, 'scripts/staff-query-api.js'), 'utf8');
const start = src.indexOf('async function handleManualBookingCreate(');
const end = src.indexOf('\nasync function ', start + 30);
const handler = src.slice(start, end);
assert.ok(start >= 0 && handler.length > 1000);
assert.doesNotMatch(handler, /MANUAL_BOOKING_ENABLED/);
assert.match(handler, /assertStaffClientAccess\(user, clientSlug, res\)/);
assert.match(handler, /trustedClientSlug:\s*clientSlug/);
const route = src.slice(src.indexOf("if (pathname === '/staff/manual-bookings/create')"), src.indexOf("if (pathname === '/staff/manual-bookings/create')") + 700);
assert.match(route, /requireAuth\(req, res, 'operator'\)/);
assert.match(route, /handleManualBookingCreate\(req, res, auth\.user\)/);
assert.doesNotMatch(src, /const MANUAL_BOOKING_ENABLED\s*=|\$\{MANUAL_BOOKING_ENABLED\}/);
assert.doesNotMatch(src, /Set MANUAL_BOOKING_ENABLED|Configura MANUAL_BOOKING_ENABLED|Imposta MANUAL_BOOKING_ENABLED/);
